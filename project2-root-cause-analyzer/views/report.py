"""Page 4: Investigation Report."""

from datetime import datetime

import pandas as pd
import streamlit as st

from cause.contribution import MarginDecomposition
from cause.insights import format_change, format_pct, format_pp, format_value, top_contributors
from cause.report import (
    KPI_EXPORT_METRICS,
    findings_frame,
    investigation_contribution_frame,
    kpi_comparison_frame,
    report_markdown,
    run_investigation,
    to_csv_bytes,
)
from ui.components import (
    METHODOLOGY,
    callout,
    causation_note,
    empty_state,
    finding_callouts,
    page_intro,
    section,
)
from ui.filters import summarize_selection
from ui.state import get_context, investigation_controls


def render() -> None:
    ctx = get_context()
    page_intro(
        "Investigation Report",
        "A shareable summary of the current investigation, with CSV downloads. It uses the same "
        "settings and calculations as the Root Cause Investigation page.",
        ctx,
    )
    if not ctx.is_ready:
        return
    with section("Report settings", "These settings are shared with the Root Cause Investigation page.",
                 key="report-settings"):
        settings = investigation_controls(ctx)
    if settings is None:
        return
    if not ctx.is_comparable:
        empty_state("No comparison available",
                    "The report needs orders in both periods. Choose another period, comparison or "
                    "wider filters.")
        return

    result = run_investigation(ctx.current, ctx.previous, settings, ctx.comparison.label)
    generated = datetime.now()
    filters = summarize_selection(ctx.selection)
    m = result.metric

    with section(f"CAUSE investigation report: {m.label}", key="report-summary"):
        st.markdown(
            f"**Generated:** {generated:%d %b %Y, %H:%M}  \n"
            f"**Metric:** {m.label}  \n"
            f"**Current period:** {ctx.comparison.current.label} "
            f"({ctx.comparison.current.start:%d %b %Y} – {ctx.comparison.current.end:%d %b %Y})  \n"
            f"**Comparison period:** {ctx.comparison.comparison.label} "
            f"({ctx.comparison.comparison.start:%d %b %Y} – {ctx.comparison.comparison.end:%d %b %Y}), "
            f"{ctx.comparison.mode_label}  \n"
            f"**Breakdown:** {' × '.join(result.main.dimension_labels)}"
            + (f" · drill-down {result.drill_scope}" if result.drill_scope else "") + "  \n"
            f"**Filters:** " + "; ".join(f"{k}: {v}" for k, v in filters)
        )

    with section("KPI comparison", "Percentage changes for revenue, profit, orders and AOV; "
                 "percentage points (pp) for margin. Values in USD (assumed currency)."):
        st.dataframe(_kpi_display(result), hide_index=True, width="stretch", key="rep_kpis")

    left, right = st.columns(2, gap="medium")
    with left:
        _contributors(result, "positive", "Largest positive contributors")
    with right:
        _contributors(result, "negative", "Largest negative contributors")

    focused = [r.finding for r in result.findings if r.finding.category in ("driver", "margin")]
    if focused:
        with section("Revenue driver and margin findings"):
            finding_callouts(focused)

    with section("Analytical insights", "Every finding is generated by rules from the figures in this report."):
        others = [r.finding for r in result.findings if r.finding.category not in ("driver", "margin")]
        if others:
            finding_callouts(others)
        else:
            callout("No findings", "Nothing met the reporting rules.", "neutral")
        causation_note()

    with section("Methodology and limitations"):
        for title, body in METHODOLOGY:
            st.markdown(f"**{title}.** {body}")

    _downloads(result, filters, generated)


def _kpi_display(result) -> pd.DataFrame:
    rows = []
    for metric in KPI_EXPORT_METRICS:
        c = result.changes[metric]
        if metric.is_percentage:
            change, rel = format_pp(c.pp_change), "—"
        else:
            change = format_change(metric, c.absolute_change)
            rel = format_pct(c.pct_change) if c.pct_change == c.pct_change else (c.unavailable_note or "n/a")
        rows.append({"Metric": metric.label, "Comparison": format_value(metric, c.previous),
                     "Current": format_value(metric, c.current), "Change": change,
                     "% change": rel})
    return pd.DataFrame(rows)


def _contributors(result, direction: str, title: str) -> None:
    a = result.main
    col = "contribution_pp" if isinstance(a, MarginDecomposition) else "change"
    with section(title, f"By {' × '.join(a.dimension_labels)}, {result.metric.label}"
                 + (" (allocated orders)" if result.metric.value == "orders" else "")
                 + (" in percentage points" if isinstance(a, MarginDecomposition) else ""),
                 key=f"rep-{direction}"):
        top = top_contributors(a, 5, direction)
        if top.empty:
            empty_state("None", f"No group had a {direction} contribution.")
            return
        rows = []
        for _, row in top.iterrows():
            share = row["share_of_net"]
            rows.append({
                "Group": " / ".join(str(row[d]) for d in a.dimensions),
                "Contribution": format_change(result.metric, row[col]),
                "% of net change": f"{share * 100:+.1f}%" if a.shares_reliable and share == share else "—",
                "% of total movement": f"{row['share_of_gross'] * 100:+.1f}%",
            })
        st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch", key=f"rep_top_{direction}")


def _downloads(result, filters, generated) -> None:
    stamp = generated.strftime("%Y%m%d-%H%M")
    metric_slug = result.metric.value
    with section("Downloads", "CSV values are unformatted numbers: percentages in percent units, "
                 "margin changes in percentage points, money in USD."):
        c1, c2, c3, c4 = st.columns(4, gap="small")
        c1.download_button("KPI comparison (CSV)", to_csv_bytes(kpi_comparison_frame(result.changes)),
                           f"cause_kpis_{stamp}.csv", "text/csv", width="stretch", key="dl_kpis",
                           on_click="ignore")
        c2.download_button("Contributions (CSV)", to_csv_bytes(investigation_contribution_frame(result)),
                           f"cause_contributions_{metric_slug}_{stamp}.csv", "text/csv", width="stretch",
                           key="dl_contrib", on_click="ignore")
        c3.download_button("Findings (CSV)", to_csv_bytes(findings_frame(result.findings)),
                           f"cause_findings_{metric_slug}_{stamp}.csv", "text/csv", width="stretch",
                           key="dl_findings", on_click="ignore")
        c4.download_button("Full report (Markdown)",
                           report_markdown(result, filters, METHODOLOGY, generated).encode("utf-8"),
                           f"cause_report_{metric_slug}_{stamp}.md", "text/markdown", width="stretch",
                           key="dl_report", on_click="ignore")


render()
